export function icon(name, size = 40) {
  const g = G[name] || G.chip;
  let rects = '';
  g.forEach((row, y) => [...row].forEach((c, x) => {
    if (c === '#') rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
    else if (c === '+') rects += `<rect class="ac" x="${x}" y="${y}" width="1" height="1"/>`;
  }));
  return `<svg class="px-icon" viewBox="0 0 10 10" width="${size}" height="${size}" aria-hidden="true" shape-rendering="crispEdges">${rects}</svg>`;
}
